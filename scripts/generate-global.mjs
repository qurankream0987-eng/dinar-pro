// Rebuild the checked-in metadata snapshot; never called on application startup.
import iso from 'i18n-iso-countries';
import world from 'world-countries';
import { createRequire } from 'node:module';
import { writeFileSync, readFileSync } from 'node:fs';
const require = createRequire(new URL('../artifacts/api-server/package.json', import.meta.url));
const { getCountryCallingCode, isSupportedCountry } = require('libphonenumber-js');
const official = readFileSync(new URL('../lib/global/src/currencies.ts', import.meta.url),'utf8');
const currencyUpdates = { BG: 'EUR', CW: 'XCG', SX: 'XCG', SL: 'SLE', ZW: 'ZWG' }; // Reconciled against SIX List One.
const ar = new Intl.DisplayNames(['ar'], { type: 'region' });
const en = new Intl.DisplayNames(['en'], { type: 'region' });
const rows = Object.keys(iso.getAlpha2Codes()).filter(code => code !== 'XK').sort().map(countryCode => {
 const c = world.find(c => c.cca2 === countryCode);
 const callingCode = isSupportedCountry(countryCode) ? '+' + getCountryCallingCode(countryCode) : null;
 return { countryCode, countryNameAr: ar.of(countryCode), countryNameEn: en.of(countryCode), callingCode, defaultCurrencyCode: currencyUpdates[countryCode] ?? Object.keys(c?.currencies ?? {}).find(code => official.includes('\"' + code + '\"')) ?? null, flag: String.fromCodePoint(...[...countryCode].map(c => c.charCodeAt(0) + 127397)), isSelectable: true };
});
writeFileSync(new URL('../lib/global/src/countries.ts', import.meta.url), `// ISO 3166-1 snapshot; generated by scripts/generate-global.mjs. Names: Unicode CLDR/ICU.\nexport type Country = { countryCode: string; countryNameAr: string; countryNameEn: string; callingCode: string | null; defaultCurrencyCode: string | null; flag: string; isSelectable: boolean };\nexport const countries: Country[] = ${JSON.stringify(rows,null,2)};\n`);
console.log('Country registry:',rows.length);
